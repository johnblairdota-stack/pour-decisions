"""Cut the Spire model into game parts (playable Spire, step 8).

    blender -b --factory-startup -P tools/blender/spire/export_game.py

Writes
  data/spire_site.json         the playable tower: levels from L6 up, slab outline, core box, pour areas
                               A and B with the joint, both placing booms, the truck gate, line pump,
                               crane and hoist (local metres: x east, y north, z AHD)
  assets/spire/spire_site.glb  everything round it as one model: ground, streets, neighbours, the
                               cathedral, trees (simple crowns), and Spire's podium L1-L5 on site
                               (slabs, columns, props, edge screens) - built as a stage with L5 done.
The game builds the deck, the core and its jump form, and the booms itself (spire_site.gd).
glTF is Y-up: game x = local x (east), game z = -local y (south), game y = AHD + offset."""
